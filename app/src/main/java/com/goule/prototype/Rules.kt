package com.goule.prototype

internal const val MINUTE = 60_000L
internal const val HOUR = 60 * MINUTE
internal const val DAY = 24 * HOUR
internal const val EDIT_INTERVAL = 5 * MINUTE
internal const val DEFAULT_USE = 20
internal const val DEFAULT_BLOCK = 30

/** Half-open interval of confirmed interactive foreground usage, in rule-clock milliseconds. */
internal data class UsageSpan(val start: Long, val end: Long)

internal data class Rule(
    val packageName: String,
    val label: String,
    val useMinutes: Int,
    val blockMinutes: Int,
    val createdAt: Long,
    val editedAt: Long? = null,
    val usage: List<UsageSpan> = emptyList(),
    val activeUseMinutes: Int? = null,
    val activeBlockMinutes: Int? = null,
    val blockedFrom: Long? = null,
    // Only for upgrading a legacy fixed block; never generated by rolling-window accounting.
    val legacyBlockedUntil: Long? = null,
    // Persist the observation watermark so repeated/overlapping callbacks cannot count twice.
    val accountedUntil: Long? = null,
) {
    val usedMs: Long get() = usage.sumOf { it.end - it.start }
    private val useLimitMs: Long get() = (activeUseMinutes ?: useMinutes) * MINUTE
    private val windowMs: Long get() = useLimitMs + (activeBlockMinutes ?: blockMinutes) * MINUTE

    // At this instant the oldest usage starts leaving the window. It does NOT reset the quota.
    val blockedUntil: Long? get() {
        val release = usage.firstOrNull()?.let { if (usedMs >= useLimitMs) it.start + windowMs else null }
        return listOfNotNull(release, legacyBlockedUntil).maxOrNull()
    }

    fun isBlocked(now: Long) = refresh(now).blockedUntil?.let { it > now } == true
    fun remainingUseMs(now: Long): Long {
        val current = refresh(now)
        return if (current.legacyBlockedUntil != null) 0 else
            (current.useLimitMs - current.usedMs).coerceIn(0, current.useLimitMs)
    }

    fun nextCheckDelayMs(now: Long): Long {
        val current = refresh(now)
        current.blockedUntil?.takeIf { it > now }?.let { return it - now }
        val remaining = (current.useLimitMs - current.usedMs).coerceAtLeast(0)
        // Zero headroom can still allow 1:1 replacement. Check its next boundary without
        // spinning every millisecond throughout the whole expiring foreground segment.
        val boundary = if (remaining > 0) remaining else
            current.usage.firstOrNull()?.let { it.end + current.windowMs - now } ?: 1_000L
        return boundary.coerceIn(1, 1_000)
    }
    fun editWait(now: Long) = editedAt?.let { (it + EDIT_INTERVAL - now).coerceAtLeast(0) } ?: 0
    fun removeWait(now: Long) = (maxOf(createdAt, blockedFrom ?: createdAt) + HOUR - now).coerceAtLeast(0)

    fun refresh(now: Long): Rule {
        val cutoff = now - windowMs
        val retained = usage.mapNotNull { span ->
            if (span.end <= cutoff) null else UsageSpan(maxOf(span.start, cutoff), span.end)
        }
        val legacy = legacyBlockedUntil?.takeIf { it > now }
        val empty = retained.isEmpty() && legacy == null
        return copy(usage = retained, legacyBlockedUntil = legacy,
            activeUseMinutes = activeUseMinutes.takeUnless { empty },
            activeBlockMinutes = activeBlockMinutes.takeUnless { empty })
    }

    fun record(delta: Long, now: Long): Rule {
        if (delta <= 0) return refresh(now)
        var cursor = maxOf(now - delta, accountedUntil ?: Long.MIN_VALUE)
        if (cursor >= now) return this
        var current = refresh(cursor)
        // A previously covered interval was blocked, even if the callback arrives after release.
        if (current.isBlocked(cursor)) return current.refresh(now).copy(accountedUntil = now)
        while (cursor < now) {
            current = current.refresh(cursor)
            val cutoff = cursor - current.windowMs
            val oldest = current.usage.firstOrNull()
            val expiring = oldest != null && oldest.start <= cutoff
            val expiryBoundary = oldest?.let {
                (if (expiring) it.end else it.start) + current.windowMs
            } ?: now
            // While old foreground time expires, incoming foreground time can replace it 1:1.
            val available = if (expiring) now - cursor else current.useLimitMs - current.usedMs
            val duration = minOf(now - cursor, expiryBoundary - cursor, available)
            if (duration <= 0) break
            val end = cursor + duration
            val spans = current.usage.toMutableList()
            if (spans.lastOrNull()?.end == cursor) {
                spans[spans.lastIndex] = UsageSpan(spans.last().start, end)
            } else spans.add(UsageSpan(cursor, end))
            current = current.copy(usage = spans,
                activeUseMinutes = current.activeUseMinutes ?: current.useMinutes,
                activeBlockMinutes = current.activeBlockMinutes ?: current.blockMinutes)
                .refresh(end)
            cursor = end
            if (current.isBlocked(cursor)) {
                current = current.copy(blockedFrom = cursor)
                break
            }
        }
        return current.refresh(now).copy(accountedUntil = now)
    }

    fun edit(use: Int, block: Int, now: Long): Rule {
        if (use == useMinutes && block == blockMinutes) return this
        check(editWait(now) == 0L)
        val current = refresh(now)
        return current.copy(useMinutes = use, blockMinutes = block, editedAt = now)
    }
}

/** Counts only intervals bounded by confirmed observations on both clocks. */
internal fun observedUsage(previousUptime: Long, previousElapsed: Long, uptime: Long, elapsed: Long): Long {
    val awake = uptime - previousUptime
    val real = elapsed - previousElapsed
    return if (awake in 0..2_000L && real - awake in -5..100L) awake else 0
}


internal fun restoreRuleTime(
    savedTime: Long, savedElapsed: Long, elapsed: Long, wall: Long, sameBoot: Boolean,
): Long = when {
    savedTime == 0L -> wall
    sameBoot && elapsed >= savedElapsed -> savedTime + elapsed - savedElapsed
    else -> maxOf(savedTime, wall)
}
